def build_seed_links() -> List[Tuple[str, str, float, Optional[dict]]]:
    """返回种子因果边列表（去重）。"""
    seen = set()
    out = []
    for cause, effect, weight, cond in SEED_LINKS:
        key = (cause, effect)
        if key in seen:
            continue
        seen.add(key)
        out.append((cause, effect, weight, cond))
    return out


def install_seed(graph, save: bool = True) -> int:
    """把种子因果边写入 CausalGraph。返回新增边数。"""
    n = 0
    for cause, effect, weight, cond in build_seed_links():
        if not graph.has_edge(cause, effect):
            graph.add_causal_link(cause, effect, weight=weight, conditions=cond,
                                  meta={"source": "seed"})
            n += 1
    if save:
        graph.save()
    return n
